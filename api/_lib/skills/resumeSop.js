export const RESUME_SOP = `# 简历修改 SOP

## 一、语体：简历书面体，不是口语
1. 省略主语（不写"我""我们"），以动词或能力短语开头；短句之间用分号连接，结尾不加"的工作""等事情"。
2. 用书面动词和名词短语：搭建、拆解、制定、复盘、推动、统筹、产出、上线；不用"帮忙""弄""搞""做了一下""挺""比较"。
3. 一条 bullet 一个主价值；不要把 4–5 件事用顿号塞进一句。
4. 既不口语，也不浮夸：不用"赋能""闭环""抓手"一类空话，也不要每句都套"通过……实现……"。读起来应当像一个真实的人写的专业简历。
   ❌ 帮团队把每周的数据整理了一下，然后发现新店的稿子比较容易被选上，就调整了一下投稿方向
   ✅ 复盘 33 篇历史稿件的收录情况，发现新开业酒店资讯更易被选用，据此调整选题与投稿，后续收录结果印证了判断

## 二、每条经历的结构：STAR 简历体
5. 默认按 STAR 组织，但压缩成一句话的逻辑链，不机械写出"情境/任务/行动/结果"四个字：
   S/T（场景或问题，半句）→ A（你的判断与关键动作，主体）→ R（结果、规模或产出物）。
   模板：能力小标题：针对[问题/场景]，[判断或方法]，[关键动作]；[结果/产出]
6. 按岗位类型选侧重：
   - 业务/运营/营销/产品：场景 → 分析 → 判断 → 动作 → 结果；
   - 技术/AI：问题 → 方案 → 关键机制或取舍 → 指标/上线结果；AI 项目要写出模型边界、评测与迭代；
   - 研究/用研：研究问题 → 方法与样本 → 个人贡献 → 发现与产出。
7. A 部分要写出你自己的判断：定了什么标准、发现了什么规律、为什么选这个方案、建议是否被采纳。这是和"岗位说明书"的区别——删掉公司名后能放进任何 JD 的句子，就是没写出判断。
8. 有前后对比时，用"旧做法的问题 → 你的改法 → 收益"的演进写法，比平铺功能更有力。
   ✅ Clipping Report 需逐条查原帖、下载归档，单份约 2 小时；拆解重复步骤后搭建素材处理 Agent，保留人工复核，单份降至约 30 分钟
9. 流程类工作可以用箭头压成一段链路（每条最多一处），例：问卷设计 → 回收 25 份 → 配对 T 检验 → OLS 回归。
10. 每段经历 2–4 条（和岗位越相关写得越多）；每条以"能力关键词小标题："开头，4–8 个字，用岗位常见说法（✅ "达人筛选与市场复盘：" ❌ "工作内容：" "提升商家入驻率："）。正文一般 40–90 字。

## 三、动词与归因
11. 责任动词按真实程度选：协助 < 参与 < 负责 < 独立负责 < 主导。可以往上靠到事实允许的最高一级，但不能越级。
12. 只写候选人原文里有的数字，不新增、不估算。数字要能和本人动作对上（动作 → 中间影响 → 结果）；只能证明参与时，写"参与推动""在项目周期内达到"，不要把相关性写成因果。
13. 团队、账号、市场或竞品的整体数据，只能作背景并写明"监测/覆盖范围"，不能写成个人成果。
14. 没有量化结果时，写真实的上线、采用、验收、覆盖范围、交付物或外部认可；原文本来就是约数的，保留"约""+"的写法。
15. 说法可以在事实范围内往强了写：动词用到事实允许的最高级，知名品牌/公司放在句首，几个真实口径里选最大的那个。不编经历和数字——面试会追问，背调会核实。
16. 拿不准的地方列进"需要你确认"清单，写清楚要确认什么，不替候选人决定。

## 四、删什么
17. 琐碎执行（领奖品、发快递、开会、发帖），除非岗位正好需要，改写成"规模 + 结果"或删掉。
18. 无证据的自评与空话（学习能力强、沟通能力强、熟练使用 ChatGPT）。
19. 技能栏不添加原文没有的技能；JD 要求而候选人没写的，放进"需要你确认"。
20. 不写课程成绩；同一件事只说一次。

## 五、写完自查
21. 每条都能经得起追问"怎么做的？为什么这么判断？数字怎么算的？"，答不上来就降级措辞或删掉。
22. 检查有没有"岗位说明书""流水账""数字装饰""实习生写得像高管"这四种失败模式。
23. 格式统一：全角中文标点，日期统一写 2024.07 – 2024.11，地点和日期写成"上海 | 2024.07 – 2024.11"。`;
