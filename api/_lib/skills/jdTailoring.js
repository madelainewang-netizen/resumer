export const JD_TAILORING_SKILL = `# 岗位定制改写 Skill

## 第一步：读岗位
从 JD 分析里挑出这个岗位最看重的 3–5 项能力（写进 focus），并记下 JD 对每项能力的原话说法。
例：AI 产品经理岗 → 需求分析与 PRD、AI 能力边界判断、数据分析、跨团队推进。

## 第二步：给每条经历找"对口能力"
逐条问自己：这条经历里，哪个事实最能证明 focus 中的某项能力？
- 直接对口：经历本身就是这项能力（例：做过 PRD → 需求分析与 PRD）。
- 可迁移：经历换了场景，但用到的是同一种能力（例：为品牌定达人筛选标准 → 制定评估标准；整理活动数据找规律 → 数据分析；对接 Agency 推进上线 → 跨团队推进）。
- 确实无关：找不到任何对口能力。这种条目应当压短到一句，让位给更相关的内容，而不是原样保留。

## 第三步：按对口能力改写（事实一个字都不能多）
可用的手法，按优先级：
1. 换小标题：小标题改成第一步里该能力的说法。原小标题是行业说法、而岗位是另一个方向时，这一步几乎总是需要的。
2. 调语序：把证明这项能力的那半句提到最前面，其他背景压缩成半句或删掉。
3. 换用词：原文的行业术语换成目标岗位能听懂的说法（例：投放复盘 → 数据复盘；KOL 资源库 → 合作方资源库），前提是意思不变。
4. 删无关：删掉与这个岗位无关、又占篇幅的半句。

## 什么时候可以保持原文（keep）
只有同时满足下面三条才 keep：
- 小标题已经是这个岗位的能力说法；
- 最相关的事实已经在句首；
- 没有与岗位无关的半句。
岗位方向与简历原方向不同时（例：营销经历投产品岗、投用研岗），绝大多数条目都不满足以上三条，应当 rewrite。
如果最后 keep 的条目超过一半，请在 overall 里说明为什么这份简历已经贴合岗位。

## 跨方向改写示例（只示范手法，事实以候选人原文为准）
原文（营销实习）：达人筛选与市场复盘：为港台新马 4 个市场设定 4 项达人筛选标准，搭建 50 人 KOL 资源库；按月整理双品牌 MIV 数据，拆解高贡献媒体与内容
→ 投用户研究岗：筛选标准设计与数据复盘：为 4 个市场制定 4 项达人筛选标准并据此评估候选人；按月整理双品牌 MIV 数据，拆解高贡献媒体与内容
→ 投 AI 产品岗：评估标准制定与数据分析：按 4 项标准为 4 个市场筛选合作达人，按月拆解 MIV 数据中的高贡献媒体与内容
（注意两个改写都没有新增任何事实，只换了小标题、语序和用词。）

## 输出要求
- focus：第一步挑出的 3–5 项能力，用 JD 的说法。
- overall：一句话说明这次改写的整体思路，例如"简历原方向偏营销，这次把达人筛选、数据复盘改写为评估标准制定和数据分析，对应产品岗的需求判断和数据能力"。
- 每条 bullet 的 reason 要写清楚用了哪种手法、对应 focus 里的哪项能力。`;
